/** Group live (non-resolved) alerts the way Alertmanager would — by alertname
 *  + tenant + site — and attach the routed receiver. Deterministic ordering. */
export function alertGroups(): AlertGroup[] {
  const groups = new Map<string, AlertGroup>();
  for (const a of ALERT_INSTANCES) {
    if (a.state === "resolved") continue;
    const key = `${a.alertname}·${a.tenant}·${a.site}`;
    const existing = groups.get(key);
    if (existing) {
      existing.members.push(a.id);
    } else {
      groups.set(key, {
        key,
        labels: { alertname: a.alertname, tenant: a.tenant, site: a.site, severity: a.severity },
        receiver: routeReceiver(a),
        members: [a.id],
      });
    }
  }
  return [...groups.values()];
}

/** Walk the routing tree and return the first matching receiver id. */
export function routeReceiver(a: AlertInstance): string {
  const labels: Record<string, string> = {
    severity: a.severity,
    owner_team: a.ownerTeam,
    tenant: a.tenant,
  };
  let receiver = ALERT_ROUTE_TREE.receiver;
  for (const child of ALERT_ROUTE_TREE.children ?? []) {
    if (matches(child.match, labels)) {
      receiver = child.receiver;
      break;
    }
  }
  return receiver;
}

function matches(match: Record<string, string>, labels: Record<string, string>): boolean {
  return Object.entries(match).every(([k, v]) => labels[k] === v);
}

export const receiverById = (id: string): AlertReceiver | undefined =>
  ALERT_RECEIVERS.find((r) => r.id === id);
